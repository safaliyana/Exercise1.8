package Area;

public class circle {

	public static void main(String[] args) {
		double radius = 6.5;
        double pi = 3.14159;
        double perimeter = 2 * radius * pi;
        double area = radius * radius * pi;
        
        System.out.println("Perimeter: " + perimeter);
        System.out.println("Area: " + area);
	}

}
